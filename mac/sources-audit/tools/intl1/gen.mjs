export function shortUrl(u) {
  const x = new URL(u);
  const segs = x.pathname.split('/').filter(Boolean).map((s) => (/[a-z]-[a-z]/i.test(s) && s.length > 18 ? '…' + (s.match(/[-_](\d{5,}|[a-z0-9]{8,}\d[a-z0-9]*)(\.html)?$/i)?.[0] || '') : s));
  const q = [...x.searchParams.keys()];
  return x.host.replace(/^www\./, '') + '/' + segs.join('/') + (q.length ? ` ?${q.join('&')}` : '');
}

