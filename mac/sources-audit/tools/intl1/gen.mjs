function kindOf(x, a) {
  for (const [re, k] of JUNK) if (re.test(x.text)) return k;
  const walled = a.site?.walls?.length || a.site?.truncatedAfterLoad;
  if (walled && (x.type === 'p' || x.type === 'h' || x.type === 'li') && x.len >= 40) return '유료벽 뒤 본문(사이트는 감춤)';
  if (x.type === 'cap') return '사진 설명(사이트와 글자 다름)';
  if (x.idx <= 3 && x.type === 'p' && x.len <= 260) return '부제·요약문';
  if (x.type === 'li' || x.type === 'h') return '관련 글 목록';
  return '기타 문단';
}
