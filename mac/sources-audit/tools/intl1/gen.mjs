function articleRow(a, note = {}) {
  const ap = app[a.link];
  const site = a.site || {};
  const ld = site.ld?.body || 0;
  const blocked = [401, 403, 429].includes(site.status) || /captcha-delivery/.test((site.embeds || []).join());
  const walledSite = site.walls?.length && a.cmp && a.cmp.siteChars < a.cmp.ourChars * 0.5;
  // 얻은 길: 앱 대조(실제 앱)가 기준, 재현과 다르면 같이 적음
  let way = ap ? (ap.ok ? `${{ fast: '빠른 길', embedded: '실린 자료', slow: '느린 길' }[ap.trace.path] || ap.trace.path} ${ap.seconds.toFixed(1)}초` : `실패(${ap.reason || ap.trace.path})`) : '-';
  if (ap && a.trace && ap.ok && a.trace.path !== ap.trace.path) way += ` (재현: ${a.trace.path}${a.trace.http ? ' ' + a.trace.http : ''})`;
  let ratio = '-', ref = '';
  const ourChars = a.cmp?.ourChars ?? (a.ours || []).filter((b) => b.text && b.type !== 'cap').reduce((s, b) => s + b.text.length, 0);
  if (note.ratio) ratio = note.ratio;
  else if (a.cmp && (walledSite || blocked) && ld) { ratio = `${ourChars} / ${ld}ᴸ (${Math.round((ourChars / ld) * 100)}%)`; ref = 'ld'; }
  else if (a.cmp && walledSite) ratio = `${ourChars} / 사이트는 ${a.cmp.siteChars}자만 보임(유료벽)`;
  else if (a.cmp && a.cmp.siteChars) ratio = `${a.cmp.ourChars} / ${a.cmp.siteChars} (${a.cmp.pct}%)`;
  else if (blocked) ratio = '사이트 차단';
  // 빠진 것
  let missing = [], cov = null;
  if (ref === 'ld') cov = Math.min(100, Math.round((ourChars / ld) * 100));
  if (a.cmp && !ref) {
    const real = a.cmp.missing.filter((m) => !MISS_JUNK.test(m.text) && m.tag !== 'figcaption');
    if (!walledSite && a.cmp.siteChars) {
      const lost = real.filter((m) => m.tag !== 'table').reduce((n, m) => n + m.len, 0);
      cov = Math.max(0, Math.round(((a.cmp.siteChars - lost) / a.cmp.siteChars) * 100));
      if (!note.ratio) ratio += ` · 사이트 글의 ${cov}% 있음`;
    }
    const by = {};
    for (const m of real) { const k = `${pos(m.idx, m.n)} ${{ p: '문단', li: '목록', h2: '소제목', h3: '소제목', h4: '소제목', blockquote: '인용', table: '표', pre: '코드' }[m.tag] || m.tag}`; by[k] = (by[k] || 0) + 1; }
    missing = Object.entries(by).map(([k, v]) => `${k} ${v}`);
    const promo = a.cmp.missing.length - real.length;
    if (promo) missing.push(`(사이트 홍보·안내 ${promo} — 빠져도 됨)`);
    if (a.cmp.shape.siteTable > 0 && !real.some((m) => m.tag === 'table')) missing.push(`표 ${a.cmp.shape.siteTable}`);
    if (a.cmp.shape.sitePre > a.cmp.shape.ourPre) missing.push(`코드 ${a.cmp.shape.sitePre - a.cmp.shape.ourPre}`);
  }
  // 섞인 것
  const mixed = {};
  let hiddenBody = 0;
  if (a.cmp) for (const x of a.cmp.extra) { const k = kindOf(x, a); if (k.startsWith('유료벽')) { hiddenBody++; continue; } mixed[k] = (mixed[k] || 0) + 1; }
  if (hiddenBody && !/유료벽/.test(ratio)) ratio += ` · 사이트가 감춘 본문 ${hiddenBody}문단을 앱은 얻음`;
  else if (hiddenBody) ratio += ` · 감춘 ${hiddenBody}문단을 앱은 얻음`;
  const mixedStr = Object.entries(mixed).map(([k, v]) => `${k}${v > 1 ? ' ' + v : ''}`).join(' · ');
  // 사진
  let pic = '-';
  if (a.cmp) {
    const im = a.cmp.imgs;
    pic = `사이트 ${im.site} / 우리 ${im.ours}` + (im.ourCaps ? ` · 설명 ${im.ourCaps}` : '') + (im.capOrphans ? ` · 짝 잃은 설명 ${im.capOrphans}` : '');
  } else if (a.ours) pic = `우리 ${a.ours.filter((b) => b.type === 'img').length}`;
  const cover = ap?.cover ? `표지 ${ap.coverFrom} ${ap.coverSize || '?'}${ap.coverNote ? ' ⚠︎' + ap.coverNote : ''}` : (ap ? '표지 없음' : '');
  return {
    cells: [`\`${shortUrl(a.link)}\` — ${a.why}`, way, ratio, (note.missing ?? (missing.join(' · ') || '없음')), (note.mixed ?? (mixedStr || '없음')), [pic, cover].filter(Boolean).join(' · '), note.tr || '-', note.memo || ''],
    pct: 'cov' in note ? note.cov : cov,
    ok: ap ? ap.ok : !!a.ours, mixedKinds: Object.keys(mixed), blocked: ap && !ap.ok && /차단/.test(ap.reason || ''),
  };
}

